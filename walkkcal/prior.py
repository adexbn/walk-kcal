# ★★ 调料 / 碟料：**词尾锚定**才是稳的（2026-10-15 补）
#
#   起因（实测，凌河路场景）：
#     火锅店的推荐菜里列着「现炸辣椒油」「祖传麻酱碗料」——
#     它们是**蘸料**，却因为菜品词表没命中而走 L3 兜底，
#     按门店业态估成「火锅 700 卡」上了卡片。
#
#   ★ 为什么不并进 `CATEGORY_WORDS` 精确匹配：
#     那张表是**精确匹配**。而调料在真实数据里几乎总是**组合词**
#     （「现炸辣椒油」「祖传麻酱碗料」「秘制芝麻酱」）——精确匹配必漏。
#     这正是「奶咖」那次的同一个坑（表里有 `奶咖` 却匹配不到「鲜萃奶咖」）。
#
#   ★ 为什么用 `endswith` 而不是 `in`（子串）：
#     词尾锚定天然避开误伤 ——
#       「麻酱拌面」「辣椒油拌面」结尾是「面」→ **保留**（正经菜）
#       「麻酱菠菜」「麻酱鸡丝」结尾是「菜/丝」→ **保留**（凉菜）
#       「豆瓣酱炒饭」结尾是「饭」→ **保留**
#     若用子串匹配，上面这些全会被误杀。
#
#   ★ 离线验证（改任何一条前都要重跑）：
#     在**全库真实菜名**上跑一遍，看翻转清单与误伤。
#     2026-10-15 实测 734 条 unique 菜名：新增剔除 **2 条**
#     （现炸辣椒油 / 祖传麻酱碗料），误伤 **0**，
#     反向检查（含调料词根但词尾不是调料）**0 条**。
# ═══════════════════════════════════════════════════════════════════
SEASONING_TAIL = (
    u'辣椒油', u'麻酱', u'碗料', u'蘸料', u'沾料', u'油碟', u'干碟', u'小料',
    u'味碟', u'调料', u'酱料', u'蘸水', u'蘸酱', u'底料',
    u'辣椒面', u'辣椒粉', u'辣椒酱', u'豆瓣酱', u'甜面酱', u'沙茶酱',
    u'芝麻酱', u'花生酱', u'油醋汁', u'烧烤料',
)


def is_seasoning_item(name):
    u"""是不是「调料 / 碟料」（蘸碟、碗料、酱料），而不是一道菜。

    ★ 只认**词尾** —— 见上面 SEASONING_TAIL 的说明。
    """
    n = (name or u'').strip()
    return bool(n) and n.endswith(SEASONING_TAIL)


def is_menu_item(name):
    u"""★ 这道菜该不该出现在卡片上（**全项目唯一入口**）。

    五类剔除：
      ① 品类/餐次词（「单人餐」「堂食」「下午茶」）    — is_category_word
      ② 喝的（「鲜萃奶咖」「柠檬气泡饮」「美式」）    — is_drink_item
      ③ 甜的（「蛋挞」「冰淇淋」）                    — is_sweet_item
      ④ 食材/加料（「螃蟹」「鸡翅」「泡菜」）          — is_shallow_item
      ⑤ 调料/碟料（「现炸辣椒油」「祖传麻酱碗料」）    — is_seasoning_item
    """
    n = (name or u'').strip()
    if not n or len(n) < 2:
        return False
    if not _RE_HAS_WORD.search(n):          # ★ 纯符号 / 价格串（`¥12`）
        return False
    if is_category_word(n):
        return False
    if is_drink_item(n) or is_sweet_item(n) or is_shallow_item(n):
        return False
    if is_seasoning_item(n):
        return False
    return True


def is_drink_only_store(store):
    u"""★ 这家店是不是「只卖喝的」—— **store 级**判据（与 `select._is_drink_only` 等价）。

    为什么要在这里再写一份：
      渲染阶段会**丢掉「一道可用菜都没有」的店**（`render.py` 的象限分桶里）。
      纯柠檬茶店以前靠「柠檬茶」这道菜活过渲染、到筛选阶段才被隐去（**会计入
      「已隐去 N 家」**）；现在「柠檬茶」被正确识别为饮品后，它在**渲染阶段**
      就先没了 —— 如果不管，脚注数字会凭空变小，变成「静默消失」。

    所以渲染阶段丢弃它时，要用**同一个判据**认出来并计数。

    ★ 必须与 `select._is_drink_only` 逐字等价（含 `dishes` 字段），
      由 `tests/test_gate.py::test_drink_only_parity` 守着 —— 两套实现漂移过，
      是本项目曾经出过错的地方。
    ★ `filter` 只能**函数内懒导入**：`filter.py` 在模块级 `from prior import
      MEAL_WORDS`，模块级互导会成环。
    """
    from walkkcal import filter as _f
    inds = set(_f.classify(store))
    if inds & _f.MEAL_INDUSTRIES:
        return False                       # 挂着正餐业态 → 不是只卖喝的
    if not (inds & _f.DRINK_ONLY_INDUSTRIES):
        return False                       # 不是饮品类目 → 不适用
    names = list(store.get('dish_hints') or [])
    names += [(d.get('name') if isinstance(d, dict) else d)
              for d in (store.get('dishes') or [])]
    return not any(_f.has_meal_word(n) for n in names if n)


def dish_prior(dish):
    u"""L2：按菜名关键词定品类。返回 (kcal, 品类名) 或 (None, None)"""
    for rx, k, n in DISH_RE:
        if rx.search(dish or ''):
            return k, n
    return None, None


def store_prior(store):
    u"""L3：按门店业态/品类定品类。返回 (kcal, 品类名) 或 (None, None)

    store 可以是：
      · dict —— 结构化线索，键：
            'industries'   归一化业态列表（最可靠，来自地图 provider）
            'text'         品类线索 + 店名
            'dish_names'   该店的推荐菜名（**最后的**弱信号：
                            「这家店在卖面包」→ 按西点估）
      · str  —— 线索串，约定：`industries` 用 `/` 连接放开头，
                其后是品类线索与店名（见 `packs/registry._store_hint`）。

    ★ 分三级、不混在一起：业态 → 品类线索/店名 → 推荐菜名。
      混在一起会互相污染（例：一家火锅店的菜名里有「面包」，
      若把菜名和店名同等对待，就会判成西点）。
    ★ 与地图服务商无关：只认归一化业态 + 通用中文词。
    """
    inds, text, dishes = [], u'', []
    if isinstance(store, dict):
        inds = list(store.get('industries') or [])
        text = store.get('text') or u''
        dishes = list(store.get('dish_names') or [])
    else:
        s = store or u''
        head, _, text = s.partition(u';')
        inds = [x for x in head.split(u'/') if x]

    for ind in inds:                      # ① 归一化业态（最可靠）
        if ind in INDUSTRY_PRIOR:
            k, n = INDUSTRY_PRIOR[ind]
            return k, n
    for rx, k, n in STORE_RE:             # ② 品类线索 / 店名
        if text and rx.search(text):
            return k, n
    for rx, k, n in STORE_RE:             # ③ 推荐菜名（弱信号，最后用）
        for d in dishes:
            if rx.search(d):
                return k, n
    return None, None




def estimate(dish, store_type=None):
    u"""兜底估算入口。

    返回 dict：{kcal, tier, label, category} 或 None（弃权）
      tier: 'L2' | 'L3'
      label: 可直接展示在界面上的来源说明
    """
    # ★ 与 `is_menu_item` 保持一致：调料/碟料不该被估成一道菜
    #   （否则直接调 estimate 的路径会绕过卡片过滤，给「辣椒油」估 700 卡）
    if is_category_word(dish) or is_seasoning_item(dish):
        return None
    k, n = dish_prior(dish)
    if k:
        return {'kcal': k, 'tier': 'L2',
                'label': u'品类估算（%s）' % n, 'category': n}
    # ★ 素菜/配菜单独一档（插在门店兜底之前，见上方 VEG_* 注释）
    if is_veg_item(dish):
        k, n = veg_prior(dish)
        return {'kcal': k, 'tier': 'L2',
                'label': u'品类估算（%s）' % n, 'category': n}
    k, n = store_prior(store_type)
    if k:
        return {'kcal': k, 'tier': 'L3',
                'label': u'同类估算（%s）' % n, 'category': n}
    return None


