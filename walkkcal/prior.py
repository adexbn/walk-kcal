def is_veg_item(name):
    u"""这道菜是不是**素菜/配菜**（可以按素菜档给数，而不是掉到门店档）"""
    n = (name or u'').strip()
    if not n or not VEG_RE.search(n):
        return False
    if VEG_MAIN.search(n) or VEG_MEAT.search(n):
        return False
    return True


def veg_prior(name):
    u"""素菜分档：凉菜/白灼 100 ・ 清炒时蔬 150 ・ 重油做法 250"""
    n = name or u''
    if any(w in n for w in VEG_COLD):
        return 100, u'素菜·凉'
    if any(w in n for w in VEG_OILY):
        return 250, u'素菜·重油'
    return 150, u'素菜'

