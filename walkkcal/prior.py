#     · 椰乳奶饮：椰乳／生打椰／椰椰／牛乳／牛奶／奶白／奶绿／珍奶／热鲜奶
#       （**用「热鲜奶」而不是裸「鲜奶」**—— 后者会命中「炸鲜奶」）
#     · 其它：气泡（替代原「气泡饮|气泡水|气泡美式」三条）／油柑／水蜜桃／
#       玫柠／青柠／耶加雪菲／奶白酒／酒酿
DRINK_RE = re.compile(
    u'拿铁|卡布|摩卡|澳白|冷萃|浓缩|玛奇朵|馥芮白|奶咖|咖啡'
    u'|奶茶|果茶|茶饮|奶盖|波波|甘露|芝芝|雪顶|乳茶|茶后|茶王'
    u'|奶昔|冰沙|沙冰|圣代|气泡|柠檬水|柠檬茶|柠檬红|椰子水|鲜榨|果汁'
    u'|苏打|汽水|饮品|生椰|星冰乐|思慕雪'
    u'|红茶|冰茶|桃桃茶|耶加雪菲'
    u'|瑞纳冰|桃桃冰|冰芒|融融冰|西瓜冰|冰茉莉|杨梅冰|百香果'
    u'|椰乳|生打椰|椰椰|牛乳|奶白|奶绿|珍奶|热鲜奶'
    u'|油柑|水蜜桃|玫柠|青柠|奶白酒|酒酿|酸奶|厚乳|金桔柠檬'
    # ★ 2026-10-15 外地四城回归补：酸梅汤（9 次出现）、鸡尾酒（3 次）、果粒橙。
    #   用「鸡尾酒」而不是「鸡尾」—— 「鸡尾虾」是正经冷盘；
    #   用「果粒橙」而不是「橙」—— 裸「橙」会命中「香橙蒸蛋」「橙香鸭」。
    u'|酸梅汤|鸡尾酒|果粒橙')

# 「喝的」——**词尾锚定**（复用 `SEASONING_TAIL` 的范式）
#   ★ 只认词尾：`鲍汁扣鹅掌` 尾字是「掌」→ 不命中；
#     而「雪梨汁/甘蔗汁/玉米汁/果蔬汁/酸角汁」「小麦胚芽饮/元气姨妈饮」全收。
#     若用子串匹配，「饮食」「果汁杯」之类会被误杀。
#   ★ `牛奶` 必须用尾锚定而不是子串 —— 离线验证抓到唯一一条误伤：
#     `法式牛奶超软吐司`（那是**面包**，含 `MEAL_WORDS` 的「吐司」）。
#     尾锚定后「芒果牛奶 / 木瓜牛奶 / 奇异果香蕉牛奶」照收，
#     而「法式牛奶超软吐司」（尾字「司」）安然保留。
DRINK_TAIL = (u'汁', u'饮', u'牛奶')

# 「喝的」——**英文/拉丁词**（独立成表，不并入上面的中文表）
#   ★ 为什么独立：① 中文表加 `re.I` 无意义（中文无大小写），
#     混在一起会让「哪条规则管什么」变模糊；② 边界写法完全不同。
#   ★ 为什么用 lookaround 而不是 `\b`：`\b` 对「中英相连」失效 ——
#     「玫瑰fizz」里 `玫` 与 `f` 同属 `\w`，`\bfizz` 匹配不上。
#     这里的 lookaround **只按拉丁字母设边界**。
#   ★ 这样 `Steak` 不会被 `tea` 误伤（左右都是字母 → 被挡住）。
#   ★ 不加 `shake`（会命中 Shake Shack）/ `cola`（→可乐鸡翅）/ `soda`（→Soda bread）。
DRINK_EN_RE = re.compile(
    u'(?<![A-Za-z])'
    u'(?:cappuccino|espresso|americano|macchiato|frappuccino|affogato'
    u'|latte|mocha|frappe|smoothie|milkshake|fizz|cocktail|juice'
    u'|coffee|tea|cold\\s?brew|flat\\s?white)'
    u'(?![A-Za-z])', re.I)

# 「甜的」信号（甜点 / 冰淇淋）—— 用户 2026-10-13 裁定：这是「喝的和甜的」，
#   不是「吃饭」。与原 `render._DESSERTS` 行为保持一致（不倒退）。
SWEET_RE = re.compile(
    u'冰淇淋|冰激凌|淇淋|甜筒|圣代|雪糕|布丁|双皮奶|慕斯|提拉米苏|杨枝甘露'
    u'|西米露|银耳羹|红豆沙|水果捞|蛋挞|甜甜圈|可丽饼|松饼|华夫饼|舒芙蕾'
    u'|雪媚娘|班戟|清补凉|凉糕|龟苓膏|糖藕|拔丝|糍粑|西点|蛋糕|泡芙')


def has_meal_word(name):
    u"""这道菜名看着能当一餐吗（含主食/烘焙/单品正餐信号）？"""
    return any(w in (name or u'') for w in MEAL_WORDS)


def is_drink_item(name):
    u"""这道菜是不是「喝的」？

    ★★ 「美式」看**位置**，不看长度（2026-10-15 用户指正）：
        「美式汉堡」和「美式咖啡」是两件事 ——
          · 美式做**后缀**（「美式」「冰美式」「热美式」「XX气泡美式」）
            → 是咖啡 ✓
          · 美式做**前缀**（「美式豪情牛肉培根菠萝比萨」「美式汉堡」）
            → 通常是菜 ✗
        「美式咖啡」也属前缀，但它含「咖啡」，由 `DRINK_RE` 兜住。
      原来的判据是「含美式 且 ≤6 字」，能挡住那个 13 字的比萨，
      却挡不住「美式汉堡」这类短名 —— 换成位置判断后两种都对。
    ★ 三条并列：中文词根（子串）／英文词（按拉丁字母设边界）／词尾（汁·饮）。
    """
    n = (name or u'').strip()
    if not n:
        return False
    if n.endswith(u'美式'):
        return True
    return bool(DRINK_RE.search(n) or DRINK_EN_RE.search(n)
                or n.endswith(DRINK_TAIL))


def is_sweet_item(name):
    u"""这道菜是不是「甜的」（甜点/冰淇淋）—— 不算「吃饭」"""
    return bool(SWEET_RE.search(name or u''))


def is_shallow_item(name):
    u"""这个词是不是「食材 / 加料」而不是一道菜。

    ★ 判据 = **≤2 字 且 没有任何菜品信号**。
      「螃蟹 / 鸡翅 / 大虾 / 泡菜 / 玉米 / 豆腐 / 鸡爪」→ 是食材 ✓
      「拌面 / 炒饭 / 米线 / 牛排 / 烧鹅」→ 有信号，是菜 ✓
    """
    n = (name or u'').strip()
    if len(n) > 2:
        return False
    return not has_meal_word(n)


