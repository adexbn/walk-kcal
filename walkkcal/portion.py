# 保底：找不到对应时按「一道菜/一份」的常见克数
DEFAULT_PORTION_G = 250

# 份数上下限 —— 超过说明这配方是「整桌菜」
MIN_SERVINGS = 1.0
MAX_SERVINGS = 40.0


# ═══════════════════════════════════════════════════════════════════
# ★ bug⑭：规格型菜名直接决定份数
#   「生日蛋糕8英寸」与「生日蛋糕10英寸」热量差 56%，但配料一模一样 ——
#   不看名字就会算出同一个数（实测两个都是 230 卡）。
#   判据：名字里有尺寸/规格词时，按面积或容量比例折算份数。
# ═══════════════════════════════════════════════════════════════════
import re as _re

# 直径类（圆）：面积 ∝ 直径²。基准 8 寸切成 8 块。
_CAKE_SLICES = 8
_SIZE_BASE = 8.0

# 规格词 → (数值, 单位类别)  单位类别：'inch' 直径 / 'ml' 体积
_SIZE_RE = _re.compile(r'(\d+(?:\.\d+)?)\s*(英寸|寸|吋|cm|厘米|ml|毫升|L|升|杯|个|只|条|克|g|人份|人)')


def _servings_from_name(dish_name):
    """
    从菜名解析「规格缩放系数」。返回 (系数, 说明) 或 None。

    ★ 语义：语料库配方本身是**一个基准规格的整只**，
      所以这里算的是「目标规格 ÷ 基准规格」的**放大倍数**，
      不是「切成几块」。
      误用会导致：8寸蛋糕和10寸蛋糕算出相同热量（bug⑭）。

    例：'生日蛋糕8英寸'  → (1.00, 8)   基准就是 8 寸
        '生日蛋糕10英寸' → (1.56, 10)  面积比 (10/8)²
        '生日蛋糕12英寸' → (2.25, 12)
    """
    m = _SIZE_RE.search(dish_name)
    if not m:
        return None
    try:
        val = float(m.group(1))
    except ValueError:
        return None
    unit = m.group(2)

    if unit in (u'英寸', u'寸', u'吋', u'cm', u'厘米'):
        # 圆蛋糕：面积 ∝ 直径² → 放大倍数
        return max(0.2, min(6.0, (val / _SIZE_BASE) ** 2)), val
    if unit in (u'ml', u'毫升', u'L', u'升', u'杯'):
        # 饮品：基准 500ml 一份
        return max(0.2, min(6.0, val / 500.0)), val
    if unit in (u'人', u'人份'):
        return max(1.0, min(20.0, val)), val
    if unit in (u'个', u'只', u'条'):
        return max(0.2, min(10.0, val)), val
    return None


def apply_name_scale(servings, dish_name):
    """
    把「按主料推断的份数」用菜名规格修正。
    语料库配方是基准规格 → 先还原成「整只」，再按目标规格缩放。
      servings=3（一锅 3 份基准规格）+ '10英寸' → 3 / 1.56 = 1.92 份 10 寸
    """
    sc = _servings_from_name(dish_name)
    if not sc:
        return servings
    return max(1.0, servings / sc[0])


def estimate_servings(ings, parsed=None, dish_name=None):
    """
    从配料估算这个配方做了几份。
    ings: 原始配料字符串列表
    parsed: 可选，预先解析好的 (g, name, state) 列表，省一次解析
    dish_name: 菜名 —— 尺寸/规格型菜（8寸蛋糕 vs 10寸）必须按名字区分
    返回 (servings, driver_name, driver_g)
    """
    if parsed is None:
        from walkkcal import core
        parsed = [core.parse_ingredient(s) for s in ings]

    # ★ bug⑭：规格型菜（8寸/10寸蛋糕、500ml/1000ml 饮品）无法可靠归一化 ——
    #   语料库配方本身**没有标出自己的规格**（下厨房 0% 有份量字段），
    #   所以「一个 10 寸蛋糕配方」到底是几寸无从得知。
    #   实测按面积比缩放后 6寸(337) > 8寸(230)，方向都反了。
    #   结论：规格型菜直接弃权，而不是给一个看着正常但错的数。
    if dish_name and _servings_from_name(dish_name):
        return None, u'规格无法归一', None

    best = 0.0
    who = None
    who_g = None
    total_g = 0.0
    best_kcal = 0.0            # ★ bug⑮：用「热量贡献」选驱动主料，而非「份数」

    for (g, name, state) in parsed:
        if not name:
            continue
        std = PORTION_G.get(name)
        # 模糊匹配：「猪五花肉」→ 找 PORTION_G 里最接近的键
        if std is None:
            for k, v in PORTION_G.items():
                if k in name or name in k:
                    std = v
                    break
        if not g or not std:
            continue
        # 调味料类不该决定份数
        if state == 'seasoning':
            continue
        s = g / float(std)
        total_g += g
        # ★ bug⑮：原逻辑取「份数最大」的那项作驱动，导致
        #   「20个鹌鹑蛋(400g,÷15=26份)」压过「500g五花肉(÷130=3.8份)」，
        #   算出 16-26 份 → 每份热量低到不合理，整道菜被闸门拦掉。
        #   正确做法：按**热量贡献**选驱动 —— 真正决定这道菜分量的是主料。
        if parsed is not None:
            from walkkcal import core as _core   # ★ 必须显式导入
            kcal_g = _core.kcal_of(name) or 0
        else:
            kcal_g = 0
        contrib = g * kcal_g
        if contrib > best_kcal:
            best_kcal = contrib
            best, who, who_g = s, name, g

    if best <= 1.0:
        # 主料都没超过一份 → 可能本来就是单人份，但也可能是「适量」没克数
        # 用总量兜底：总重超过 400g 至少不是一人份
        if total_g > 400:
            best = total_g / DEFAULT_PORTION_G
            who, who_g = u'总重', int(total_g)
        else:
            return 1.0, None, None

    best = max(MIN_SERVINGS, min(MAX_SERVINGS, best))
    return best, who, who_g
