"""
可信度闸门 —— 解决「白斩鸡 32 卡」「蛋炒饭 219 卡」这类致命错误

verify_portion.py 实测暴露的两个独立病根：

  病根 A：份量不对（语料库 0% 有 servings 字段）
    肉夹馍 2102卡（500克五花肉+500克面粉=一锅），小馄饨 1975卡（500克猪肉=十几碗）

  病根 B：主料被整段漏算（配料写「适量肉」「适量米饭」时，主料热量为 0）
    白斩鸡 32卡 —— 鸡在哪？蛋炒饭 219卡 —— 米饭没算进去
    ★ 这比 A 更致命：算出来的数字不是「偏了」而是「完全错」，且看起来正常

对策：两道闸门，宁可报「算不出」也不给假数字。

  闸门 1（治 B）：主料闸 —— 一个配方必须至少有一个「主料类」食材被成功解析且有克数，
         否则这个配方的热量必然大残 → 直接剔除，不参与中位数
  闸门 2（治 A）：合理性闸 —— 按菜品类别设定人均可食量的合理区间，
         落在区间外的配方 → 剔除；多数配方都落空 → 整道菜判为不可信

  置信度：
    high   ≥6 个配方且区间跨度 <2.2 倍
    medium ≥3 个配方
    low    2 个配方
    none   过不了闸门 → 展示为「数据不足」，不给数字
"""

# ═══════════════════════════════════════════════════════════════════
# 主料类食材 —— 这些漏了整个配方就废了
# ═══════════════════════════════════════════════════════════════════
