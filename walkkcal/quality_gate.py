DEFAULT_RANGE = (80, 700)


def category_of(dish_name):
    for kw, lo, hi, cn in CATEGORY_RANGE:
        if kw in dish_name:
            return lo, hi, cn
    return DEFAULT_RANGE[0], DEFAULT_RANGE[1], u'菜品'


def main_ingredient_parsed(ings, parsed):
    """
    闸门 1：主料是否被成功解析并有克数。
    返回 (通过?, 命中的主料名, 该主料克数)
    判定：配料里出现主料关键词，且至少一个被解析成有克数的已知食材
    """
    hit_kw, parsed_ok = None, None
    for (g, name, state), raw in zip(parsed, ings):
        label = name or str(raw)
        is_main = any(k in label for k in MAIN_PROTEIN + MAIN_STAPLE + MAIN_OTHER)
        if not is_main:
            continue
        if hit_kw is None:
            hit_kw = label
        if g and name and state in ('exact', 'range'):
            parsed_ok = (label, g)
            break
    return (parsed_ok is not None), hit_kw, parsed_ok


def plausible(dish_name, kcal_per_serving):
    lo, hi, cn = category_of(dish_name)
    return (lo <= kcal_per_serving <= hi), (lo, hi), cn
