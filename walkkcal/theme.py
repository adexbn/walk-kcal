# ★ 酒吧必须放在最后判定，且关键词收窄。
#   实测误判：「望江酒楼」「千灯状元楼」「好酒家酿」都含「酒」字被误判成酒吧 ——
#   中式餐厅名里带「酒」极常见（酒楼/酒家），这是比「清吧」更普遍的用法。
BAR_KW = (u'清吧', u'酒吧', u'bar', u'Bar', u'BAR', u'啤酒屋', u'pub', u'Pub')
DEFAULT_CATEGORY = 'restaurant'   # 面馆/粥店/米线/中式小炒/茶餐厅 全部落到「碗」


def category_of(store):
    """门店 → (图标 key, 显示名)。

    store 可以是归一化门店（含 `industries`），也可以是
    老调用方式 {'name':…, 'tags':[推荐菜], 'type':…}。
    """
    inds = list(store.get('industries') or [])          # ① 归一化业态
    for ind in inds:
        if ind in INDUSTRY_ICON:
            return INDUSTRY_ICON[ind]

    # ② 文本兜底
    name = store.get('name', u'')
    hay = u' '.join([name] + [t for t in (store.get('tags') or [])]
                    + [store.get('category_hint', u''),
                       store.get('type', u'').replace(';', u' ')])
    for kws, key, label in CATEGORY_RULES:
        for kw in kws:
            if kw in hay:
                return key, label
    # 酒吧放最后：命中即判定，避免「酒楼」被当酒吧
    for kw in BAR_KW:
        if kw in name or kw in hay:
            return 'bar', u'酒吧'
    return DEFAULT_ICON



